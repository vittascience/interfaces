#
# Implémente :
#   - constantes : MONO_VLSB, MONO_HLSB, MONO_HMSB, RGB565, GS2_HMSB, GS4_HMSB, GS8
#   - FrameBuffer(buffer, width, height, format, stride=width)
#   - format supporté : GS4_HMSB (4 bits / pixel, 2 pixels / octet, horizontal MSB)
#   - méthodes : fill, pixel, hline, vline, line, rect, fill_rect, scroll, blit
#
# À compléter si tu veux d'autres formats ou text/ellipse/poly.

