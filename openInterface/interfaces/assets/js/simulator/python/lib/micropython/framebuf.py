class FrameBuffer:
    def __init__(self, buffer, width, height, format, stride=None):
        self.width = int(width)
        self.height = int(height)
        self.format = format
        self.stride = int(stride) if stride is not None else self.width
        self.buf = buffer

        # On ne gère que GS4_HMSB dans cette implémentation
        if self.format != GS4_HMSB:
            raise ValueError("Ce port Skulpt de framebuf ne supporte que GS4_HMSB pour l'instant")

        # 4 bits / pixel => 2 pixels / octet
        bpp = 4
        pixels = self.stride * self.height
        bytes_needed = (pixels * bpp + 7) // 8
        if len(self.buf) < bytes_needed:
            raise ValueError("Buffer trop petit pour width/height/stride en GS4_HMSB")

    # ---------- helpers internes ----------

    def _check_bounds(self, x, y):
        return 0 <= x < self.width and 0 <= y < self.height

    def _index_gs4_hmsb(self, x, y):
        """
        GS4_HMSB : 4 bits par pixel, horizontal, MSB à gauche
        -> 2 pixels par octet
        pixel 0 : bits 7..4
        pixel 1 : bits 3..0
        """
        idx = y * self.stride + x          # index du pixel "logique"
        byte_index = idx // 2              # 2 pixels / octet
        pixel_in_byte = idx % 2            # 0 ou 1
        shift = 4 if pixel_in_byte == 0 else 0
        return byte_index, shift

    # ---------- API publique ----------

    def pixel(self, x, y, c=None):
        """
        pixel(x, y)       -> lit le pixel (0..15)
        pixel(x, y, col)  -> écrit le pixel
        """
        x = int(x)
        y = int(y)

        if not self._check_bounds(x, y):
            if c is None:
                return 0
            return

        byte_index, shift = self._index_gs4_hmsb(x, y)
        b = self.buf[byte_index]

        if c is None:
            # lecture
            return (b >> shift) & 0x0F

        # écriture (4 bits)
        c &= 0x0F
        mask = ~(0x0F << shift) & 0xFF
        b = (b & mask) | (c << shift)
        self.buf[byte_index] = b

    def fill(self, c):
        """
        Remplit tout le buffer avec la couleur c (0..15)
        """
        c &= 0x0F
        # pack 2 pixels dans un octet
        packed = (c << 4) | c
        for i in range(len(self.buf)):
            self.buf[i] = packed

    def hline(self, x, y, w, c):
        """
        Ligne horizontale de longueur w
        """
        x = int(x)
        y = int(y)
        w = int(w)
        if w <= 0:
            return
        x_end = x + w
        for ix in range(x, x_end):
            self.pixel(ix, y, c)

    def vline(self, x, y, h, c):
        """
        Ligne verticale de hauteur h
        """
        x = int(x)
        y = int(y)
        h = int(h)
        if h <= 0:
            return
        y_end = y + h
        for iy in range(y, y_end):
            self.pixel(x, iy, c)

    def line(self, x1, y1, x2, y2, c):
        """
        Ligne générale (Bresenham), comme framebuf.line()
        """
        x1 = int(x1)
        y1 = int(y1)
        x2 = int(x2)
        y2 = int(y2)
        c = int(c)

        dx = abs(x2 - x1)
        dy = -abs(y2 - y1)
        sx = 1 if x1 < x2 else -1
        sy = 1 if y1 < y2 else -1
        err = dx + dy

        while True:
            self.pixel(x1, y1, c)
            if x1 == x2 and y1 == y2:
                break
            e2 = 2 * err
            if e2 >= dy:
                err += dy
                x1 += sx
            if e2 <= dx:
                err += dx
                y1 += sy

    def rect(self, x, y, w, h, c, f=False):
        """
        Rectangle, bord ou plein selon f
        """
        x = int(x)
        y = int(y)
        w = int(w)
        h = int(h)
        if w <= 0 or h <= 0:
            return

        if f:
            self.fill_rect(x, y, w, h, c)
            return

        # bord
        self.hline(x, y, w, c)             # haut
        self.hline(x, y + h - 1, w, c)     # bas
        self.vline(x, y, h, c)             # gauche
        self.vline(x + w - 1, y, h, c)     # droite

    def fill_rect(self, x, y, w, h, c):
        """
        Rectangle plein
        """
        x = int(x)
        y = int(y)
        w = int(w)
        h = int(h)
        if w <= 0 or h <= 0:
            return
        y_end = y + h
        for iy in range(y, y_end):
            self.hline(x, iy, w, c)

    def scroll(self, xstep, ystep):
        """
        Décale le contenu du framebuffer (comme framebuf.scroll)
        """
        xstep = int(xstep)
        ystep = int(ystep)

        # snapshot des pixels
        tmp = []
        for y in range(self.height):
            row = []
            for x in range(self.width):
                row.append(self.pixel(x, y))
            tmp.append(row)

        # réécriture décalée
        for y in range(self.height):
            for x in range(self.width):
                sx = x - xstep
                sy = y - ystep
                if 0 <= sx < self.width and 0 <= sy < self.height:
                    col = tmp[sy][sx]
                else:
                    col = 0
                self.pixel(x, y, col)

    def blit(self, fbuf, x, y, key=-1, palette=None):
        """
        Blit simplifié :
          - source = autre FrameBuffer
          - même format GS4_HMSB
          - key et palette ignorés pour l'instant
        """
        x = int(x)
        y = int(y)

        # accepter un tuple comme dans la doc : (buffer, width, height, format[, stride])
        if not isinstance(fbuf, FrameBuffer):
            if isinstance(fbuf, (tuple, list)):
                if len(fbuf) == 4:
                    src_buf, w, h, fmt = fbuf
                    src_stride = w
                elif len(fbuf) == 5:
                    src_buf, w, h, fmt, src_stride = fbuf
                else:
                    raise ValueError("tuple/list fbuf invalide pour blit()")
                fbuf = FrameBuffer(src_buf, w, h, fmt, src_stride)
            else:
                raise TypeError("fbuf doit être un FrameBuffer ou un tuple/list")

        if fbuf.format != self.format:
            raise ValueError("blit(): formats différents non gérés dans cette version")

        for sy in range(fbuf.height):
            dy = y + sy
            if dy < 0 or dy >= self.height:
                continue
            for sx in range(fbuf.width):
                dx = x + sx
                if dx < 0 or dx >= self.width:
                    continue
                col = fbuf.pixel(sx, sy)
                if key != -1 and col == key:
                    continue
                self.pixel(dx, dy, col)

    def text(self, s, x, y, col):
        x = int(x)
        y = int(y)
        col = int(col) & 0x0F

        for ch in s:
            glyph = FONT_8X8.get(ch)
            if glyph is None:
                x += 8
                continue

            for row in range(8):
                line = glyph[row]
                for bit in range(8):
                    if line & (0x80 >> bit):
                        self.pixel(x + bit, y + row, col)

            x += 8  # caractère suivant

    # ------- Méthodes non implémentées (facultatives) -------
    def ellipse(self, x, y, xr, yr, c, f=False, m=0xF):
        raise NotImplementedError("FrameBuffer.ellipse() n'as pas encore été implémenté")

    def poly(self, x, y, coords, c, f=False):
        raise NotImplementedError("FrameBuffer.poly() n'as pas encore été implémenté")
