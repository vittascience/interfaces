/**
 * @fileoverview Reverse translation of the MicroPython chronometer blocks (io_initChronometer, io_getChronometer).
 * The interface declares "t0" in the RESERVED_WORDS of its code2Blocks/imports.js.
 */
import utils from '/openInterface/interfaces/assets/js/code2blocks/python/utils/utils.js';

// Chronometer of the "utime" module (MicroPython) or of the "time" module (ex: Eliobot)
for (const module of ['utime', 'time']) {
    const ticksMs = `${module}.ticks_ms()`;
    const delta = `${module}.ticks_diff(${module}.ticks_ms(),t0)`;

    // "utime.ticks_diff(utime.ticks_ms(), t0)" (milliseconds; an interface may define its own translation)
    utils.prototypeBlocks[`${module}.ticks_diff`] = function () {
        return {
            type: 'io_getChronometer',
            fields: { UNIT: 'MILLI' },
            values: {},
            mutations: null,
            statementsNode: null,
            statement: null
        };
    };

    // "utime.ticks_diff(utime.ticks_ms(), t0)/1e3" (seconds) and "/1e-3" (microseconds)
    utils.binaryInterceptors[`${module}.ticks_diff_DIVIDE`] = function (left, operator, right) {
        const units = { '1e3': 'SEC', '1e-3': 'MICRO' };
        if (utils.rmSpaces(left.text) !== delta || !units[right.text]) return null;
        return {
            type: 'io_getChronometer',
            fields: { UNIT: units[right.text] },
            values: {},
            mutations: null,
            statementsNode: null,
            statement: null
        };
    };
}

// Chronometer: "t0 = utime.ticks_ms()". Its first occurrence is the initialization generated by the chronometer
// blocks (ignored when other chronometer blocks are in the program), the others are "io_initChronometer" blocks.
utils.prototypeBlocks['t0'] = function (right) {
    const module = utils.rmSpaces(right.text).match(/^(u?time)\.ticks_ms\(\)$/)?.[1];
    if (!module) return null;
    const lines = (utils.python2Blocks.code || '').split('\n').map((line) => utils.rmSpaces(line));
    const init = `t0=${module}.ticks_ms()`;
    const first = lines.indexOf(init);
    const used = lines.some((line, row) => line.includes(`${module}.ticks_diff(${module}.ticks_ms(),t0)`) || (row > first && line === init));
    if (right.start.row === first && used) return '';
    return {
        type: 'io_initChronometer',
        fields: {},
        values: {},
        mutations: null,
        statementsNode: null,
        statement: null
    };
};
